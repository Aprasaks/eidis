from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[1]
MAC=ROOT/"macos/Sources/EidisMac"
ACCOUNT=(MAC/"JarvisMetaChannels.swift").read_text()
IG=(MAC/"JarvisMetaInstagramService.swift").read_text()
UI=(MAC/"JarvisCommandCenterView.swift").read_text()
# The SNS / YouTube channel monitor moved to its own file; check both.
UI += "\n" + (MAC/"JarvisChannelMonitorView.swift").read_text()
DASH=(MAC/"JarvisLiveDashboard.swift").read_text()
STUDIO=(MAC/"JarvisWikiSocialStudio.swift").read_text()
class MetaConnections(unittest.TestCase):
    def test_three_distinct_authorization_endpoints(self):
        self.assertIn("https://graph.facebook.com/v27.0/me?fields=id,name,username",ACCOUNT)
        self.assertIn("https://graph.threads.net/v1.0/me?fields=id,username",ACCOUNT)
        self.assertIn("https://graph.instagram.com/v27.0/me?fields=id,username",IG)
        self.assertIn("https://graph.facebook.com/v27.0/",IG)
        self.assertIn("JarvisInstagramLoginMode",IG)
        self.assertIn("mode == .instagramLogin || profile.id == accountID",IG)
    def test_identity_verification_before_secure_store(self):
        self.assertIn("page.id == pageID",ACCOUNT)
        self.assertIn('profile.username?.lowercased() == "dechive.wiki"',ACCOUNT)
        self.assertIn("guard checked.connected else { return checked }",ACCOUNT)
        self.assertIn("kSecAttrAccessibleWhenUnlockedThisDeviceOnly",ACCOUNT)
        self.assertIn("kSecAttrAccessibleWhenUnlockedThisDeviceOnly",IG)
        self.assertIn("kSecReturnData as String",ACCOUNT)
        self.assertIn('request.httpMethod = "GET"',ACCOUNT)
        self.assertNotIn('request.httpMethod = "POST"',ACCOUNT)
        self.assertNotIn('request.httpMethod = "DELETE"',ACCOUNT)
        self.assertNotIn("?access_token=",ACCOUNT + IG)
        self.assertNotIn('print(token)',ACCOUNT + IG + UI)
        self.assertIn('JarvisMetaChannels.sanitizedFailure(data, status: http.statusCode)',IG)
    def test_correct_accounts_have_separate_native_ui(self):
        self.assertIn("jarvis-meta-facebook-connect",UI)
        self.assertIn("jarvis-meta-threads-connect",UI)
        self.assertIn("jarvis-instagram-token-connect",UI)
        self.assertIn("Facebook Page Access Token",UI)
        self.assertIn("Threads User Access Token",UI)
        self.assertIn("instagramLoginMode",UI)
        self.assertIn("verifyFacebook(pageID:",ACCOUNT)
        self.assertIn("verifyThreads(token:",ACCOUNT)
        self.assertIn("connectInstagram(token: String, mode:",DASH)
class Editorial(unittest.TestCase):
    def test_source_grounded_and_read_only(self):
        self.assertIn('url.host == "dechive.wiki"',STUDIO)
        self.assertIn('https://dechive.wiki/',STUDIO)
        self.assertIn('"/knowledge/([0-9a-f-]{36})"',STUDIO)
        self.assertIn('http://127.0.0.1:11434/api/chat',STUDIO)
        self.assertIn('"stream":false',STUDIO)
        self.assertIn('"format":schema',STUDIO)
        self.assertIn('sourceURL:source.url',STUDIO)
        self.assertIn('Source: " + source.url',STUDIO)
        self.assertIn("copy.facebook.count >= 160",STUDIO) if "copy.facebook.count >= 160" in STUDIO else self.assertIn("organic.allSatisfy",STUDIO)
        self.assertIn('reviewed:false',STUDIO)
        self.assertIn('PROPOSAL ONLY',STUDIO)
        self.assertIn('Budget not authorized',STUDIO)
        self.assertIn('jarvis-meta-content-studio',UI)
        self.assertIn('JarvisWikiSocialStudioView(studio: socialStudio)',UI)
        self.assertNotIn('graph.facebook.com',STUDIO)
        self.assertNotIn('graph.threads.net',STUDIO)
        self.assertNotIn('ads_management',STUDIO)
if __name__=='__main__':unittest.main()
